#!/usr/bin/env python3
"""Generate ar/index.html (the indexable Arabic page) from index.html.

Every element with class "t" carries data-en / data-ar; this script writes the
Arabic text into the HTML, switches the page to lang="ar" dir="rtl", and points
assets one folder up. Run it after every edit to index.html:

    python3 tools/build-ar.py
"""
import html, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = 'https://mohamedabuemira.github.io/'
TITLE_AR = 'محمد عصام أبو عميرة | خبير Odoo ومدير عمليات ERP'
DESC_AR = 'خبير Odoo ومدير عمليات ERP وكبير محاسبين سابق. أكثر من 82 مشروع Odoo وERP لشركات في السعودية والإمارات ومصر وليبيا.'

src = open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()
OPEN = re.compile(r'<([a-zA-Z][a-zA-Z0-9]*)\b([^>]*?\bclass="(?:[^"]*\s)?t(?:\s[^"]*)?"[^>]*?)>')


def swap_text(s):
    out, pos = [], 0
    for m in OPEN.finditer(s):
        if m.start() < pos:
            continue  # nested inside an element already swapped
        tag, attrs = m.group(1), m.group(2)
        ar = re.search(r'\sdata-ar="([^"]*)"', attrs)
        if not ar:
            continue
        # find the matching close tag
        depth, i = 1, m.end()
        tok = re.compile(r'<(/?)' + tag + r'\b[^>]*>')
        while depth:
            t = tok.search(s, i)
            if t is None:
                raise SystemExit(f'unclosed <{tag}> near: {s[m.start():m.start()+80]}')
            depth += -1 if t.group(1) else 1
            i = t.end()
        close_start = s.rfind('</' + tag, m.end(), i)
        out.append(s[pos:m.end()])
        out.append(ar.group(1))
        pos = close_start
    out.append(s[pos:])
    return ''.join(out)


s = swap_text(src)
s = re.sub(r'(<(?:input|textarea)[^>]*?data-ph-ar="([^"]*)"[^>]*?)placeholder="[^"]*"',
           lambda m: m.group(1) + 'placeholder="' + m.group(2) + '"', s)

reps = [
    ('<!-- ar/index.html is generated from this file: run `python3 tools/build-ar.py` after editing -->\n',
     '<!-- GENERATED by tools/build-ar.py from index.html. Do not edit by hand. -->\n'),
    ('<html lang="en" dir="ltr">', '<html lang="ar" dir="rtl">'),
    ('<body>', '<body class="ar">'),
    (f'<link rel="canonical" href="{URL}">', f'<link rel="canonical" href="{URL}ar/">'),
    (f'<meta property="og:url" content="{URL}">', f'<meta property="og:url" content="{URL}ar/">'),
    ('<meta property="og:locale" content="en_US">\n<meta property="og:locale:alternate" content="ar_AR">',
     '<meta property="og:locale" content="ar_AR">\n<meta property="og:locale:alternate" content="en_US">'),
    ('<a class="lang-toggle" href="ar/" hreflang="ar" lang="ar" id="langBtn">',
     '<a class="lang-toggle" href="../" hreflang="en" lang="en" id="langBtn">'),
    ('<span id="langLabel">العربية</span>', '<span id="langLabel">English</span>'),
]
for old, new in reps:
    assert s.count(old) >= 1, old
    s = s.replace(old, new)

title_en = re.search(r'<title>(.*?)</title>', s).group(1)
desc_en = re.search(r'<meta name="description" content="([^"]*)">', s).group(1)
s = s.replace(f'<title>{title_en}</title>', f'<title>{TITLE_AR}</title>')
for attr in ('name="description"', 'property="og:description"', 'name="twitter:description"'):
    s = s.replace(f'<meta {attr} content="{desc_en}">', f'<meta {attr} content="{DESC_AR}">')
for attr in ('property="og:title"', 'name="twitter:title"'):
    s = s.replace(f'<meta {attr} content="{title_en}">', f'<meta {attr} content="{TITLE_AR}">')

# assets and in-page links resolve from /ar/
s = s.replace('"./assets/', '"../assets/').replace("'./assets/", "'../assets/")

os.makedirs(os.path.join(ROOT, 'ar'), exist_ok=True)
open(os.path.join(ROOT, 'ar', 'index.html'), 'w', encoding='utf-8').write(s)
print('wrote ar/index.html')
